# and,or operator
# and,or operator is used to check two condition

country='pakistan'                                    # and operator
province = 4                                          # and return true if two condition is satisfied
if country=='pakistan' and province == 4:            
    print("condition satisfied")                   
else:
    print("condition failed")

country1='pakistan'                                    # or operator
province1=4                                            # or return false if both two or one condition is satisfied
if country1=='pakkstan' or province1==4:
    print("condition satisfied")                    
else:                                               
    print("condition failed")