# step argument
# step argument is used to print a no after some spaces.
for a in range(1,10,2):  # step argument in for loop.
    # print(f"1st line {a}")
    print(a)
for b in range(1,-7,-1):
    # print(f"2nd line {b}")
    print(b)
for c in range(5,1,-1):
    # print(f"3rd line {c}")
    print(c)
for d in range(-5,5,1):
    # print(f"4th line {d}")
    print(d)
for e in range(8,1,-2):
    # print(f"5th line {e})")
    print(e)