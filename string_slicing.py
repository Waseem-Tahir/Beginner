# string slicing/select sub sequences
subject="information technology"
print(subject[0:]) # if you dont give input then it give all data presence in subject.
print(subject[-5:23]) # your use negative idexing also.
print(subject[:14]) # it give output form start point 0 to 14 point of data.
print(subject[7:12]) # it give output form point 7 to 12.
print(subject[-8:-2]) # it give output in reverse order.