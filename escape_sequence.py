# Escape Sequence
# \n to jump next line, \t to take some space between two words and \b to delete one character.
# Escape Sequence always start with back slash \.
# if you use double backslash then it will be declared one backslash.
# if you use four bakslash then it will be declared two backslash.
print("your name is\twaseem\nyour age is ...\b.")
print("\\")   # it show only one backslash.
print("\\\\")   # it show two backslash.
