# if else statement
# if else statement is used at that time when you check multiple conditions.
no=int(input("enter the year of your date of birth: "))
nvg=int(-1)
no=(nvg*no)
if no==-2008:
    print("your age is now 18 year ")
elif no>=-2008:
    print("your age is now 18 year above ")
elif no<-2008:
    print("you are under 18 ")